    public void getTime() {
        //evito crear otro temp q sume los segs simultaneo
        if (timer == null) {
            timer = new Timer(1000, (e) -> {
                segs++;

                if (segs == 60) {
                    segs = 0;
                    mins++;
                }

                if (mins == 60) {
                    mins = 0;
                    hrs++;
                }

                if (hrs == 24) {
                    hrs = 0;
                }

                jL1.setText(String.format("%02d", segs));
                jL2.setText(String.format("%02d", mins));
                jL3.setText(String.format("%02d", hrs));
            });
        }
        timer.start();
    }

